use crate::config::DnsConfig;
use std::path::Path;
use std::time::Instant;
use tokio::fs;
use tracing::{info, warn};

/// Applies the DNS configuration to the system (/data/resolv.conf.head and /tmp/resolv.conf)
pub async fn apply_dns(cfg: &DnsConfig) -> Result<(), String> {
    // Only attempt system DNS modification if /tmp or /data exists (e.g. Linux on Station)
    if !Path::new("/tmp").exists() && !Path::new("/data").exists() {
        info!("Host does not have /tmp or /data; skipping system DNS modification");
        return Ok(());
    }

    if cfg.custom_enabled {
        let prim = if cfg.primary_dns.trim().is_empty() {
            "1.1.1.1"
        } else {
            cfg.primary_dns.trim()
        };
        let sec = cfg.secondary_dns.trim();

        let mut resolv_content = String::new();
        resolv_content.push_str("# Configured by station_daemon (Custom DNS)\n");
        resolv_content.push_str(&format!("nameserver {}\n", prim));
        if !sec.is_empty() && sec != prim {
            resolv_content.push_str(&format!("nameserver {}\n", sec));
        }

        // 1. Write /data/resolv.conf.head for persistence across dhcpcd renewals & reboots
        if Path::new("/data").exists() {
            if let Err(e) = fs::write("/data/resolv.conf.head", &resolv_content).await {
                warn!("Failed to write /data/resolv.conf.head: {}", e);
            }
        }

        // 2. Write /tmp/resolv.conf for instant, real-time application
        if Path::new("/tmp").exists() {
            if let Err(e) = fs::write("/tmp/resolv.conf", &resolv_content).await {
                warn!("Failed to write /tmp/resolv.conf: {}", e);
            }
        }

        info!(
            "Applied custom DNS (provider: {}): primary={}, secondary={}",
            cfg.provider, prim, sec
        );
    } else {
        // Revert to system / router DHCP DNS
        if Path::new("/data/resolv.conf.head").exists() {
            let _ = fs::remove_file("/data/resolv.conf.head").await;
        }

        // Restore /tmp/resolv.conf: point to 127.0.0.1 (Unbound) or default
        if Path::new("/tmp").exists() {
            let default_resolv = "# Generated by dhcpcd\nnameserver 127.0.0.1\n";
            let _ = fs::write("/tmp/resolv.conf", default_resolv).await;
        }

        info!("Reverted DNS to system default (DHCP / Unbound 127.0.0.1)");
    }

    Ok(())
}

/// Retrieves list of currently active DNS nameservers from /tmp/resolv.conf or /etc/resolv.conf
pub async fn get_active_nameservers() -> Vec<String> {
    let mut servers = Vec::new();

    let path = if Path::new("/tmp/resolv.conf").exists() {
        "/tmp/resolv.conf"
    } else if Path::new("/etc/resolv.conf").exists() {
        "/etc/resolv.conf"
    } else {
        return servers;
    };

    if let Ok(content) = fs::read_to_string(path).await {
        for line in content.lines() {
            let line = line.trim();
            if line.starts_with("nameserver ") {
                if let Some(ip) = line.split_whitespace().nth(1) {
                    if !servers.contains(&ip.to_string()) {
                        servers.push(ip.to_string());
                    }
                }
            }
        }
    }

    servers
}

/// Tests DNS resolution for a given hostname, returning resolved IP and latency in ms
pub async fn test_dns_resolution(host: &str) -> Result<(String, u64), String> {
    let target_host = if host.trim().is_empty() {
        "cloudflare.com"
    } else {
        host.trim()
    };

    let start = Instant::now();
    let res = tokio::net::lookup_host((target_host, 80u16)).await;
    let elapsed_ms = start.elapsed().as_millis() as u64;

    match res {
        Ok(mut addrs) => {
            if let Some(addr) = addrs.next() {
                Ok((addr.ip().to_string(), elapsed_ms))
            } else {
                Err(format!("Хост {} не вернул IP-адресов", target_host))
            }
        }
        Err(e) => Err(format!("Ошибка разрешения {}: {}", target_host, e)),
    }
}
